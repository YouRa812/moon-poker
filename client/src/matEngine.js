// Функция выбора случайной матерной реплики
export function getRandomMat(category, subcategory = null) {
  let list = MAT_DICTIONARY[category];
  if (!list) return "Блядь!";
  if (subcategory && list[subcategory]) {
    list = list[subcategory];
  }
  if (Array.isArray(list)) {
    return list[Math.floor(Math.random() * list.length)];
  }
  return "Ёбаный рот!";
}
